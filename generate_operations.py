#!/usr/bin/env python3
"""Generate deterministic fixed-operation JS contracts and public documentation."""
import argparse
import json
from pathlib import Path
from operation_registry import REGISTRY, PAGE_OPERATIONS, BACKGROUND_OPERATIONS, GLOBAL_OPERATIONS

ROOT = Path(__file__).resolve().parent


def outputs():
    catalog = {'registryVersion': REGISTRY['registryVersion'], 'productVersion': REGISTRY['productVersion'],
               'pageOperations': sorted(PAGE_OPERATIONS), 'backgroundOperations': sorted(BACKGROUND_OPERATIONS),
               'globalOperations': sorted(GLOBAL_OPERATIONS), 'operations': REGISTRY['operations']}
    js = '/* Generated by generate_operations.py. Edit operations.json / operation_validator.js instead. */\n(() => {\nconst catalog = ' + json.dumps(catalog, sort_keys=True, separators=(',', ':')) + ';\n' + (ROOT / 'operation_validator.js').read_text() + '\n})();\n'
    lines = ['# Operation contracts', '', 'Generated from `operations.json`; do not edit this file.', '',
             'Baseline means the oldest version tested for this catalog, not the first version introducing a command.',
             'These contracts describe declared support; live capabilities and backend preconditions remain authoritative.',
             'An operation completing does not establish that a site saved its effects.', '',
             '| Operation | Engine | Effect | Ordering | Platforms | Baseline |', '|---|---|---|---|---|---|']
    for name, spec in sorted(REGISTRY['operations'].items()):
        lines.append('| ' + ' | '.join([name, spec['engine'], spec['effect'], spec['ordering'], ', '.join(spec['platforms']), spec['baselineVersion']]) + ' |')
    lines += ['', '## Input schemas', '', 'Machine-readable per-operation input schemas live in `operations.json` and the generated extension catalog.',
              '`operation_registry.validate_arguments()` validates the supported JSON Schema subset without dependencies, including every batch step before dispatch.',
              'The generated JavaScript validator checks inputs before Firefox dispatch, including the entire batch with inherited tab/workflow arguments. Native companion contracts remain separate.', 'Output schemas describe successful raw Firefox results before compaction, not MCP envelopes or errors. `validate_result()` / `validateResult()` are explicit conformance helpers, not post-mutation rejection. Extensible diagnostic objects and site-defined WebMCP result payloads intentionally permit additional fields.', '']
    return {ROOT / 'extension/operations.generated.js': js, ROOT / 'docs/OPERATIONS.md': '\n'.join(lines)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail rather than write when generated files are stale')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.exit(1, 'Stale generated contracts: ' + ', '.join(stale) + '\n')


if __name__ == '__main__':
    main()
