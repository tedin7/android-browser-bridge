const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('apps/task-panel.html', 'utf8');
const source = html.match(/<script>([\s\S]*?)<\/script>/)[1];
const nodes = new Map();
const document = {getElementById(id) {
  if (!nodes.has(id)) nodes.set(id, {disabled: true, textContent: '', events: {}, addEventListener(event, listener) { this.events[event] = listener; }});
  return nodes.get(id);
}};
const sent = [], listeners = {}, timers = new Map(); let timerId = 0;
const parent = {postMessage(message) { sent.push(message); }};
const window = {parent, addEventListener(event, listener) { listeners[event] = listener; }};
const context = {window, document, setTimeout(fn) { timers.set(++timerId, fn); return timerId; }, clearTimeout(id) { timers.delete(id); }};
vm.runInNewContext(source, context);
const receive = (data, sender = parent, origin = 'https://owned-host.example') => listeners.message({source: sender, origin, data});
const tick = () => new Promise(resolve => setImmediate(resolve));
(async () => {
  assert.equal(sent[0].method, 'ui/initialize');
  assert.equal(sent[0].params.protocolVersion, '2026-01-26');
  receive({jsonrpc: '2.0', id: sent[0].id, result: {protocolVersion: '2026-01-26', hostCapabilities: {serverTools: {}}}}, {});
  await tick();
  assert.equal(sent.length, 1, 'Unrelated window cannot complete handshake');
  receive({jsonrpc: '2.0', id: sent[0].id, result: {protocolVersion: '2026-01-26', hostCapabilities: {serverTools: {}}}});
  await tick();
  assert.equal(sent[1].method, 'ui/notifications/initialized');
  const task = {taskId: 'fixture_task', state: 'working', progress: .5, receipt: {verified: false, actionMayHaveOccurred: true, secret: 'PRIVATE_CONTENT'}, secret: 'PRIVATE_CONTENT'};
  const result = {content: [{type: 'text', text: JSON.stringify(task)}]};
  receive({jsonrpc: '2.0', method: 'ui/notifications/tool-result', params: result});
  assert.equal(nodes.get('refresh').disabled, false);
  assert.equal(nodes.get('cancel').disabled, false);
  assert(!nodes.get('receipt').textContent.includes('PRIVATE_CONTENT'));
  receive({jsonrpc: '2.0', method: 'ui/notifications/tool-result', params: {structuredContent: {...task, taskId: 'other_task'}}});
  assert(nodes.get('receipt').textContent.includes('fixture_task'));
  nodes.get('refresh').events.click();
  let call = sent.at(-1);
  assert.equal(call.method, 'tools/call');
  assert.equal(call.params.name, 'browser_task');
  assert.deepEqual(JSON.parse(JSON.stringify(call.params.arguments)), {action: 'get', taskId: 'fixture_task'});
  receive({jsonrpc: '2.0', id: call.id, result}); await tick();
  nodes.get('cancel').events.click(); call = sent.at(-1);
  assert.equal(call.params.arguments.action, 'cancel');
  assert.equal(call.params.arguments.taskId, 'fixture_task');
  assert.equal(Object.keys(call.params.arguments).length, 2);
  receive({jsonrpc: '2.0', id: call.id, result: {structuredContent: {...task, cancelRequested: true}}}); await tick();
  assert.equal(nodes.get('cancel').disabled, true);
  assert(nodes.get('status').textContent.includes('waiting for acknowledgement'));
  receive({jsonrpc: '2.0', id: 99, method: 'ui/resource-teardown', params: {}});
  assert.equal(nodes.get('refresh').disabled, true);
  assert.equal(timers.size, 0);
  console.log('MCP Apps task panel protocol, authority and redaction tests passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
